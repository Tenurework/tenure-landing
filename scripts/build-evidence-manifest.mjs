/**
 * Resolves every evidence path in the claims register against a real checkout of
 * the product repositories, and writes the result to a committed manifest.
 *
 * WHY THIS EXISTS. `e2e/claims.spec.ts` could only ever check that an evidence
 * string LOOKED like a path — CITES_A_PATH is a regex over the shape of the text.
 * It never opened one, because CI has no checkout of `satvikOS/Tenure`. Four
 * citations passed green for months as a result: a file that does not exist
 * (`apps/web/src/components/TenureAIPanel.tsx` — the real path has an `ai/`
 * segment), a literal `...` standing in for a directory, a spec that tests
 * something else entirely, and a `ci-verified` claim naming no test at all.
 *
 * A register whose citations cannot be opened is a bibliography, not evidence.
 *
 * HOW IT WORKS. This runs where the product repos are checked out, resolves each
 * path, and records the answer alongside the commit it was resolved at. The
 * manifest is committed, and `claims.spec.ts` asserts against it in CI. That
 * moves the guarantee from "this string is shaped like a path" to "this path
 * existed in this repository at this commit, and here is when we last looked".
 *
 * The manifest can go stale — that is the honest limit of this approach, and it
 * is why the commit is recorded per entry and checked against the register's own
 * `evidenceCommit`. A drifted manifest fails loudly rather than passing quietly.
 *
 * Run: npm run claims:evidence      (needs the product repos checked out)
 */
import { existsSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import { claims } from "../src/lib/claims.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

/**
 * Where each evidence repository is checked out on this machine.
 *
 * The defaults were absolute Windows paths belonging to the one workstation this
 * script was first written on, so on every other machine it reported both product
 * repos as NOT CHECKED OUT and rewrote the manifest to nulls — silently turning
 * the evidence gate off rather than failing. Sibling directories are the
 * convention (`~/Tenure`, `~/Tenure-Parent` next to `~/tenure-landing`), and
 * `TENURE_PATH` / `TENURE_PARENT_PATH` still override for anyone laid out
 * differently.
 */
const REPOS = {
  Tenure: process.env.TENURE_PATH ?? join(root, "..", "Tenure"),
  "Tenure-Parent": process.env.TENURE_PARENT_PATH ?? join(root, "..", "Tenure-Parent"),
  "tenure-landing": root,
};

/**
 * Pulls the file path out of an evidence string.
 *
 * Entries look like "apps/web/src/lib/ai.ts:35 (fetch https://...)" or
 * "apps/web/e2e/policies.spec.ts:77-106" or, legitimately, like prose with no
 * path at all ("zero update/delete/upsert in application code"). Bracketed Next
 * route segments — `[id]`, `[slug]` — are part of the path and must survive.
 */
function pathOf(evidence) {
  const token = evidence.trim().split(/\s+/)[0];
  const bare = token.replace(/:[0-9]+(-[0-9]+)?$/, "").replace(/[,;]$/, "");
  if (!/\//.test(bare)) return null;
  if (!/\.[a-z0-9]+$/i.test(bare)) return null; // a directory, not a file
  if (bare.includes("...")) return null; // rejected separately, with a better message
  return bare;
}

function headOf(repoPath) {
  try {
    return execFileSync("git", ["-C", repoPath, "rev-parse", "--short", "HEAD"], {
      encoding: "utf8",
    }).trim();
  } catch {
    return null;
  }
}

const heads = Object.fromEntries(
  Object.entries(REPOS).map(([name, p]) => [name, existsSync(p) ? headOf(p) : null]),
);

const entries = [];
const missing = [];
let skipped = 0;

for (const c of claims) {
  const repoName = c.evidenceRepo;
  const repoPath = REPOS[repoName];
  for (const ev of c.evidence) {
    const rel = pathOf(ev);
    if (!rel) {
      skipped++;
      continue;
    }
    if (!repoPath || !existsSync(repoPath)) {
      entries.push({ claim: c.id, repo: repoName, path: rel, exists: null, at: null });
      continue;
    }
    const exists = existsSync(resolve(repoPath, rel));
    entries.push({ claim: c.id, repo: repoName, path: rel, exists, at: heads[repoName] });
    if (!exists) missing.push(`${c.id} -> ${repoName}/${rel}`);
  }
}

const manifest = {
  note:
    "Generated by scripts/build-evidence-manifest.mjs. Records whether each evidence path " +
    "in the claims register resolved against a real checkout, and at which commit. " +
    "e2e/claims.spec.ts asserts against this because CI has no product-repo checkout.",
  generated: process.env.EVIDENCE_MANIFEST_DATE ?? null,
  heads,
  entries,
};

writeFileSync(join(root, "docs", "evidence-manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

console.log(`Resolved ${entries.length} evidence paths across ${claims.length} claims.`);
console.log(`Skipped ${skipped} evidence entries that are prose rather than a file path.`);
for (const [name, head] of Object.entries(heads)) {
  console.log(`  ${name.padEnd(15)} ${head ?? "NOT CHECKED OUT"}`);
}

if (missing.length) {
  console.error(`\n${missing.length} evidence path(s) DO NOT EXIST:`);
  for (const m of missing) console.error(`  ${m}`);
  process.exit(1);
}
console.log("\nEvery evidence path resolves.");
